#!/usr/bin/env node
// Regenerates web-app/js/sim-schema.js from firmware/test/golden/schema.json.
// Run after any change to the firmware's registered modules/params, then commit
// both files -- web-app/tests/sim-schema-drift.test.js fails if they disagree.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const golden = JSON.parse(readFileSync(`${here}../../firmware/test/golden/schema.json`, 'utf8'));

const out = `// Generated by web-app/tools/gen-sim-schema.js from
// firmware/test/golden/schema.json. Do not edit by hand -- re-run the
// generator and commit the result.
export const SIM_SCHEMA = ${JSON.stringify({ params: golden.params, tlm: golden.tlm }, null, 2)};
`;

writeFileSync(`${here}../js/sim-schema.js`, out);
console.log(`wrote ${here}../js/sim-schema.js`);
